"""Generates Deskmat widget resources (drawables, layouts, appwidget-provider XML)."""
import math, os
RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res")
for d in ("drawable", "layout", "xml", "values", "values-night"):
    os.makedirs(os.path.join(RES, d), exist_ok=True)

def w(path, text):
    with open(os.path.join(RES, path), "w", encoding="utf-8", newline="\n") as f:
        f.write(text.lstrip())

HEAD = '<?xml version="1.0" encoding="utf-8"?>\n'

# ---- Dice: a rounded square with pip holes (even-odd), so one tint colours it. ----
PIPS = {
    1: [(12, 12)],
    2: [(8, 8), (16, 16)],
    3: [(7.5, 7.5), (12, 12), (16.5, 16.5)],
    4: [(8, 8), (16, 8), (8, 16), (16, 16)],
    5: [(7.5, 7.5), (16.5, 7.5), (12, 12), (7.5, 16.5), (16.5, 16.5)],
    6: [(8, 7), (16, 7), (8, 12), (16, 12), (8, 17), (16, 17)],
}

def circle(cx, cy, r=1.6):
    return f"M{cx - r},{cy}a{r},{r} 0,1 0,{2 * r},0a{r},{r} 0,1 0,{-2 * r},0z"

BODY = "M6,3h12a3,3 0,0 1,3,3v12a3,3 0,0 1,-3,3h-12a3,3 0,0 1,-3,-3v-12a3,3 0,0 1,3,-3z"

def dice(face, rotation=0.0):
    path = BODY + "".join(circle(x, y) for x, y in PIPS[face])
    return HEAD + f'''<!-- Generated by gen_widgets.py: die showing {face}, turned {rotation:g} degrees. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
    <group android:pivotX="12" android:pivotY="12" android:rotation="{rotation:g}" android:scaleX="0.92" android:scaleY="0.92">
        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{path}" />
    </group>
</vector>
'''

for f in range(1, 7):
    w(f"drawable/widget_dice_{f}.xml", dice(f))
# Roll frames: faces tumble while the die turns.
ROLL = [(3, 25), (6, 70), (2, 115), (5, 160), (1, 205), (4, 250), (6, 295), (3, 335)]
for i, (face, rot) in enumerate(ROLL):
    w(f"drawable/widget_dice_roll_{i}.xml", dice(face, rot))

w("drawable/widget_chevrons.xml", HEAD + '''<!-- Three chevrons pointing along the track: "slide this way". -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="36dp" android:height="16dp" android:viewportWidth="36" android:viewportHeight="16">
    <path android:fillColor="#FFFFFFFF" android:pathData="M2,1.5l2.5,-1.5l7,8l-7,8l-2.5,-1.5l5.7,-6.5z" />
    <path android:fillColor="#FFFFFFFF" android:pathData="M13,1.5l2.5,-1.5l7,8l-7,8l-2.5,-1.5l5.7,-6.5z" />
    <path android:fillColor="#FFFFFFFF" android:pathData="M24,1.5l2.5,-1.5l7,8l-7,8l-2.5,-1.5l5.7,-6.5z" />
</vector>
''')
w("drawable/widget_next.xml", HEAD + '''<!-- Material "fast_forward". -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
    <path android:fillColor="#FFFFFFFF" android:pathData="M4,18l8.5,-6L4,6v12zM13,6v12l8.5,-6L13,6z" />
</vector>
''')

# ---- Colours per style (light; night overrides) ----
w("values/widget_colors.xml", HEAD + '''<resources>
    <!-- Material: dynamic colour (Material You) roles. -->
    <color name="widget_m_bg">@android:color/system_accent1_100</color>
    <color name="widget_m_fg">@android:color/system_accent1_800</color>
    <color name="widget_m_track">@android:color/system_accent1_200</color>
    <color name="widget_m_thumb">@android:color/system_accent1_600</color>
    <color name="widget_m_on_thumb">@android:color/system_accent1_0</color>
    <!-- One UI (as One UI widget packs draw it): near-white capsule, dark glyphs, accent only on the control. -->
    <color name="widget_o_bg">#F2F8F8FF</color>
    <color name="widget_o_fg">#FF1A1B20</color>
    <color name="widget_o_track">#0F000000</color>
    <color name="widget_o_thumb">@android:color/system_accent1_400</color>
    <color name="widget_o_on_thumb">#FFFFFFFF</color>
    <!-- Opaque bases for the shapes: the app tints them at runtime (colour and opacity), and a
         background tint multiplies with the shape's own alpha, so the shapes themselves must be opaque.
         These are also what the widget picker's preview shows. -->
    <color name="widget_o_bg_base">#FFF8F8FF</color>
    <color name="widget_o_track_base">#FFE4E4EA</color>
</resources>
''')
w("values-night/widget_colors.xml", HEAD + '''<resources>
    <color name="widget_m_bg">@android:color/system_accent1_800</color>
    <color name="widget_m_fg">@android:color/system_accent1_100</color>
    <color name="widget_m_track">@android:color/system_accent1_700</color>
    <color name="widget_m_thumb">@android:color/system_accent1_200</color>
    <color name="widget_m_on_thumb">@android:color/system_accent1_800</color>
    <color name="widget_o_bg">#E6000000</color>
    <color name="widget_o_fg">#FFF1F0F7</color>
    <color name="widget_o_track">#17FFFFFF</color>
    <color name="widget_o_thumb">@android:color/system_accent1_400</color>
    <color name="widget_o_on_thumb">#FFFFFFFF</color>
    <color name="widget_o_bg_base">#FF000000</color>
    <color name="widget_o_track_base">#FF383838</color>
</resources>
''')
w("values/widget_dimens.xml", HEAD + '''<resources>
    <!-- One UI widgets are fully rounded (a capsule, or a circle when square); Material follows the launcher's widget radius. -->
    <dimen name="widget_o_radius">1000dp</dimen>
</resources>
''')

# Slider heights: the regular 48 dp track, and a 76 dp one for tall cells. One UI shrinks a widget
# laid out for the main screen's cells to fit the cover screen, so the track must fill the
# cell's height to keep its proportions.
# Track thicknesses (dp) in 8 dp steps; the app picks the thickest that leaves the standard gap in the
# widget's cell, and sets the exact track length at runtime.
SLIDER_SIZES = [(f"_{t}", t) for t in (40, 48, 56, 64, 72, 80)]
# Track lengths in 20 dp steps; the app picks the one that leaves equal gaps on every side.
SLIDE_LENGTHS = list(range(120, 421, 20))

STYLES = {"m": ("@android:dimen/system_app_widget_background_radius", "Material"), "o": ("@dimen/widget_o_radius", "One UI")}

for s, (radius, label) in STYLES.items():
    w(f"drawable/widget_{s}_bg.xml", HEAD + f'''<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <corners android:radius="{radius}" />
    <solid android:color="@color/widget_{s}_{'bg_base' if s == 'o' else 'bg'}" />
</shape>
''')
    for suffix, th in SLIDER_SIZES:
        w(f"drawable/widget_{s}_track{suffix}.xml", HEAD + f'''<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <corners android:radius="{th // 2}dp" />
    <solid android:color="@color/widget_{s}_{'track_base' if s == 'o' else 'track'}" />
    <size android:height="{th}dp" />
</shape>
''')
        w(f"drawable/widget_{s}_track_clear{suffix}.xml", HEAD + f'''<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="@android:color/transparent" />
    <size android:height="{th}dp" />
</shape>
''')
    for icon, suffix, th in [(i, sx, t) for i in ("next", "dice") for sx, t in SLIDER_SIZES]:
        # Thumb: a filled circle with the icon drawn in the "on thumb" colour, in one vector.
        if icon == "next":
            glyph = '<group android:translateX="12" android:translateY="12"><path android:fillColor="@color/widget_%s_on_thumb" android:pathData="M4,18l8.5,-6L4,6v12zM13,6v12l8.5,-6L13,6z" /></group>' % s
        else:
            glyph = '<group android:translateX="12" android:translateY="12" android:pivotX="12" android:pivotY="12" android:scaleX="0.92" android:scaleY="0.92"><path android:fillColor="@color/widget_%s_on_thumb" android:fillType="evenOdd" android:pathData="%s" /></group>' % (s, BODY + "".join(circle(x, y) for x, y in PIPS[5]))
        w(f"drawable/widget_{s}_thumb_{icon}{suffix}.xml", HEAD + f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{th}dp" android:height="{th}dp" android:viewportWidth="48" android:viewportHeight="48">
    <path android:fillColor="@color/widget_{s}_thumb" android:pathData="M24,0a24,24 0,1 1,0,48a24,24 0,1 1,0,-48z" />
    {glyph}
</vector>
''')

    # Next image (1x1, resizable): one icon that scales with the widget.
    w(f"layout/widget_next_{s}.xml", HEAD + f'''<!-- {label} "Next image" widget. Padding is set at runtime from Settings. -->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@android:id/background"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:background="@drawable/widget_{s}_bg"
    android:clipToOutline="true"
    android:contentDescription="Next wallpaper">
    <!-- Padding from Settings is applied as this frame's margin, in dp, so the launcher scales it for its own screen. -->
    <FrameLayout
        android:id="@+id/content"
        android:layout_width="match_parent"
        android:layout_height="match_parent">
        <ImageView
            android:id="@+id/icon"
            android:layout_width="match_parent"
            android:layout_height="match_parent"
            android:layout_margin="10dp"
            android:scaleType="fitCenter"
            android:src="@drawable/widget_next"
            android:tint="@color/widget_{s}_fg"
            android:importantForAccessibility="no" />
    </FrameLayout>
</FrameLayout>
''')

    # Slide to change: a Switch whose thumb is dragged along a long track. Several lengths per
    # orientation, picked by the launcher from the widget's size (responsive RemoteViews).
    for (length, orient, (suffix, th)) in [(l, o, z) for l in SLIDE_LENGTHS for o in ("h", "v") for z in SLIDER_SIZES]:
        if True:
            text_sp, preview = {40: 15, 48: 17, 56: 19, 64: 21, 72: 23, 80: 24}[th], th - 8
            rot = ' android:rotation="-90"' if orient == "v" else ""
            w(f"layout/widget_slide_{s}_{orient}{length}{suffix}.xml", HEAD + f'''<!-- {label} "Slide to change" widget, {"horizontal" if orient == "h" else "vertical"}, {length} dp track, {th} dp tall. -->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@android:id/background"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:background="@drawable/widget_{s}_bg"
    android:clipToOutline="true">
    <FrameLayout
        android:id="@+id/content"
        android:layout_width="match_parent"
        android:layout_height="match_parent">
    <FrameLayout
        android:id="@+id/track"
        android:layout_width="{length}dp"
        android:layout_height="{th}dp"
        android:layout_gravity="center"
        android:background="@drawable/widget_{s}_track{suffix}"{rot}>
        <!-- Optional preview of the next image at the end of the track; the thumb slides onto it. -->
        <ImageView
            android:id="@+id/preview"
            android:layout_width="{preview}dp"
            android:layout_height="{preview}dp"
            android:layout_gravity="end|center_vertical"
            android:layout_marginEnd="4dp"
            android:scaleType="fitCenter"
            android:visibility="gone"
            android:importantForAccessibility="no" />
        <TextView
            android:id="@+id/hint"
            android:layout_width="match_parent"
            android:layout_height="match_parent"
            android:layout_marginStart="{th + 6}dp"
            android:layout_marginEnd="{preview + 14}dp"
            android:gravity="center"
            android:text="Slide for next"
            android:textColor="@color/widget_{s}_fg"
            android:textStyle="bold"
            android:textSize="{text_sp}sp"
            android:autoSizeTextType="uniform"
            android:autoSizeMinTextSize="10sp"
            android:autoSizeMaxTextSize="{text_sp}sp"
            android:autoSizeStepGranularity="1sp"
            android:maxLines="1" />
        <ImageView
            android:id="@+id/chevrons"
            android:layout_width="match_parent"
            android:layout_height="{max(16, th // 3)}dp"
            android:layout_gravity="center_vertical"
            android:layout_marginStart="{th + 6}dp"
            android:layout_marginEnd="{preview + 14}dp"
            android:src="@drawable/widget_chevrons"
            android:tint="@color/widget_{s}_fg"
            android:alpha="0.6"
            android:scaleType="fitCenter"
            android:visibility="gone"
            android:importantForAccessibility="no" />
        <Switch
            android:id="@+id/slider"
            android:layout_width="wrap_content"
            android:layout_height="{th}dp"
            android:layout_gravity="start|center_vertical"
            android:showText="false"
            android:switchMinWidth="{length}dp"
            android:thumb="@drawable/widget_{s}_thumb_next{suffix}"
            android:track="@drawable/widget_{s}_track_clear{suffix}"
            android:contentDescription="Slide for next wallpaper" />
    </FrameLayout>
    </FrameLayout>
</FrameLayout>
''')

    # 30 dp minimums: One UI's launcher sometimes converts them with the phone's density on DeX
    # (40 dp became 90 px, more than one 72 px DeX row), which locked the widget at 2x2.
    # app:widgetStyle="colorful" and a real app:widgetSize are what One UI Home checks before it
    # draws its own wallpaper blur behind a widget (attrs in values/samsung_widget_attrs.xml).
    common = '''    app:widgetStyle="colorful"
    app:widgetSize="tiny|small|wideSmall|medium|large|extraLarge|extraLargeLong"
    android:configure="dev.dexwp.backdrop.widget.WidgetConfigActivity"
    android:resizeMode="horizontal|vertical"
    android:updatePeriodMillis="0"
    android:widgetCategory="home_screen|keyguard"
    android:widgetFeatures="reconfigurable|configuration_optional"'''
    w(f"xml/widget_next_{s}.xml", HEAD + f'''<appwidget-provider xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:app="http://schemas.android.com/apk/res-auto"
    android:description="@string/widget_next_desc"
    android:initialLayout="@layout/widget_next_{s}"
    android:previewLayout="@layout/widget_next_{s}"
    android:minWidth="30dp"
    android:minHeight="30dp"
    android:minResizeWidth="30dp"
    android:minResizeHeight="30dp"
    android:targetCellWidth="1"
    android:targetCellHeight="1"
{common} />
''')
    w(f"xml/widget_slide_{s}.xml", HEAD + f'''<appwidget-provider xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:app="http://schemas.android.com/apk/res-auto"
    android:description="@string/widget_slide_desc"
    android:initialLayout="@layout/widget_slide_{s}_h220_48"
    android:previewLayout="@layout/widget_slide_{s}_h220_48"
    android:minWidth="30dp"
    android:minHeight="30dp"
    android:minResizeWidth="30dp"
    android:minResizeHeight="30dp"
    android:targetCellWidth="3"
    android:targetCellHeight="1"
{common} />
''')
w("values/samsung_widget_attrs.xml", HEAD + '''<!-- Samsung One UI widget attributes (undocumented). With widgetStyle="colorful", a widgetSize and a
     semi-transparent @android:id/background, One UI Home blurs the wallpaper behind the widget. -->
<resources>
    <attr name="widgetStyle" format="integer">
        <flag name="colorful" value="0x1" />
        <flag name="monotone" value="0x2" />
    </attr>
    <attr name="widgetSize" format="integer">
        <flag name="tiny" value="0x1" />
        <flag name="small" value="0x2" />
        <flag name="wideSmall" value="0x4" />
        <flag name="medium" value="0x8" />
        <flag name="large" value="0x10" />
        <flag name="extraLarge" value="0x20" />
        <flag name="extraLargeLong" value="0x40" />
    </attr>
</resources>
''')
